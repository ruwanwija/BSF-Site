def esc(v):
    """MySQL string literal escaping."""
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return '1' if v else '0'
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v).replace('\\', '\\\\').replace("'", "''")
    return "'" + s + "'"


def sql_val(v):
    return esc(v)


def ins(table, cols, rows):
    """Build an INSERT statement for one table."""
    col_list = ', '.join(cols)
    lines = []
    for row in rows:
        vals = ', '.join(sql_val(x) for x in row)
        lines.append(f"INSERT INTO `{table}` ({col_list}) VALUES ({vals});")
    return '\n'.join(lines)


